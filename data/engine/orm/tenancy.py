"""Tenant scoping for the Craft ORM.

The tenant is bound to a database *session variable*, which row-level security
policies read. That is what makes isolation something the application cannot
forget: a query with no tenant bound returns nothing because the policy's
predicate is NULL, not because a Python `where` clause happened to be appended.

The previous model — one PostgreSQL schema per tenant, selected with
`SET search_path` — is still available through `DB.set_tenant_schema()` and is
the right answer for the handful of tenants that need physical separation. It
is no longer the default, because it migrates every tenant separately, does DDL
on the request path for each new one, and multiplies the system catalogue by
the tenant count.

Category: Core Framework (ORM).
Relations:
  - Bound as `tenant`, exposed via the `Tenant` facade.
  - `ScopeTenant` (`engine/http/middleware.py`) binds it per request;
    `QueueManager.work()` binds it per job from the job's stored `tenant_id`.
  - Policies are generated by `Blueprint.tenant_scoped()`
    (`engine/migrations/schema.py`) and audited by `dev.py db:audit-rls`.
References:
  - Guide: `documentation/orm.md#multi-tenancy`
"""
