def panel_icon(name: str) -> str:
    """Inline SVG for a named icon, falling back to a neutral dot.

    An unknown name renders the dot rather than raising: a menu item with a
    misspelled icon should still be clickable, and the missing icon is visible
    on the page — the fastest possible way to notice the typo.
    """
    return _TEMPLATE.format(path=PATHS.get(name, PATHS["dot"]))
